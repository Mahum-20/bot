"""
HTF Level Lifecycle & Overlap Manager
====================================
Implements institutional HTF Level Invalidation, Overlap Grouping, and
Trade Consumption Lifecycle Rules:

Rule One: A level / collective group becomes permanently CONSUMED upon successful trade execution.
Rule Two: Overlapping HTF levels across timeframes are grouped into one collective trading opportunity.
          Consumed state is inherited by any newly generated level overlapping a consumed group.
Rule Three: Two consecutive completed HTF candle closes beyond a level invalidate it (strictly on its source timeframe).
"""

import os
import json
import logging
import threading
import tempfile
from enum import Enum
from typing import Dict, List, Optional, Set, Tuple, Any

logger = logging.getLogger("HTFLevelLifecycle")

DEFAULT_LIFECYCLE_STORAGE_PATH = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "data",
    "htf_levels_lifecycle.json"
)


class LevelStatus(str, Enum):
    ACTIVE = "ACTIVE"
    CONSUMED = "CONSUMED"
    INVALIDATED = "INVALIDATED"


class GroupStatus(str, Enum):
    ACTIVE = "ACTIVE"
    CONSUMED = "CONSUMED"
    INVALIDATED = "INVALIDATED"
    PARTIALLY_INVALIDATED = "PARTIALLY_INVALIDATED"


class HTFLevel:
    """Represents a single institutional HTF level generated by HTFEngine."""
    def __init__(
        self,
        level_id: str,
        symbol: str,
        timeframe: str,
        level_type: str,
        top: float,
        bottom: float,
        created_time: int,
        raw_box: Optional[Dict] = None
    ):
        self.level_id = level_id
        self.symbol = symbol.upper()
        self.timeframe = timeframe.lower()
        self.level_type = level_type.lower()  # "demand" or "supply"
        self.top = max(float(top), float(bottom))
        self.bottom = min(float(top), float(bottom))
        self.created_time = int(created_time)
        self.status = LevelStatus.ACTIVE
        self.consecutive_beyond_closes = 0
        self.last_evaluated_htf_time = 0
        self.group_id: Optional[str] = None
        self.consumed = False
        self.trade_id: Optional[str] = None
        self.raw_box = raw_box or {}

    def to_dict(self) -> Dict[str, Any]:
        return {
            "level_id": self.level_id,
            "symbol": self.symbol,
            "timeframe": self.timeframe,
            "level_type": self.level_type,
            "top": self.top,
            "bottom": self.bottom,
            "created_time": self.created_time,
            "status": self.status.value,
            "consecutive_beyond_closes": self.consecutive_beyond_closes,
            "last_evaluated_htf_time": self.last_evaluated_htf_time,
            "group_id": self.group_id,
            "consumed": self.consumed,
            "trade_id": self.trade_id,
            "raw_box": self.raw_box
        }

    @classmethod
    def from_dict(cls, d: Dict[str, Any]) -> "HTFLevel":
        lvl = cls(
            level_id=d["level_id"],
            symbol=d["symbol"],
            timeframe=d["timeframe"],
            level_type=d["level_type"],
            top=d["top"],
            bottom=d["bottom"],
            created_time=d["created_time"],
            raw_box=d.get("raw_box")
        )
        lvl.status = LevelStatus(d.get("status", LevelStatus.ACTIVE.value))
        lvl.consecutive_beyond_closes = d.get("consecutive_beyond_closes", 0)
        lvl.last_evaluated_htf_time = d.get("last_evaluated_htf_time", 0)
        lvl.group_id = d.get("group_id")
        lvl.consumed = d.get("consumed", False)
        lvl.trade_id = d.get("trade_id")
        return lvl


class HTFLevelGroup:
    """Represents a collective group of overlapping HTF levels treated as ONE trading opportunity."""
    def __init__(
        self,
        group_id: str,
        symbol: str,
        level_type: str,
        constituent_ids: Optional[List[str]] = None
    ):
        self.group_id = group_id
        self.symbol = symbol.upper()
        self.level_type = level_type.lower()
        self.constituent_ids: Set[str] = set(constituent_ids or [])
        self.status = GroupStatus.ACTIVE
        self.consumed = False
        self.trade_id: Optional[str] = None
        self.top: float = 0.0
        self.bottom: float = 0.0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "group_id": self.group_id,
            "symbol": self.symbol,
            "level_type": self.level_type,
            "constituent_ids": sorted(list(self.constituent_ids)),
            "status": self.status.value,
            "consumed": self.consumed,
            "trade_id": self.trade_id,
            "top": self.top,
            "bottom": self.bottom
        }

    @classmethod
    def from_dict(cls, d: Dict[str, Any]) -> "HTFLevelGroup":
        grp = cls(
            group_id=d["group_id"],
            symbol=d["symbol"],
            level_type=d["level_type"],
            constituent_ids=d.get("constituent_ids", [])
        )
        grp.status = GroupStatus(d.get("status", GroupStatus.ACTIVE.value))
        grp.consumed = d.get("consumed", False)
        grp.trade_id = d.get("trade_id")
        grp.top = d.get("top", 0.0)
        grp.bottom = d.get("bottom", 0.0)
        return grp


class HTFLevelLifecycleManager:
    """
    Central authoritative manager for HTF level invalidation, overlap grouping,
    and single-opportunity trade consumption.
    """
    def __init__(self, storage_path: str = DEFAULT_LIFECYCLE_STORAGE_PATH):
        self.storage_path = storage_path
        self._lock = threading.Lock()
        self.levels: Dict[str, HTFLevel] = {}
        self.groups: Dict[str, HTFLevelGroup] = {}
        # Stores historical consumed price ranges: (symbol, level_type, bot, top, trade_id)
        self.consumed_price_zones: List[Dict[str, Any]] = []
        self._load()

    def _load(self):
        with self._lock:
            if os.path.exists(self.storage_path) and os.path.getsize(self.storage_path) > 0:
                try:
                    with open(self.storage_path, "r", encoding="utf-8") as f:
                        data = json.load(f)
                    for l_data in data.get("levels", []):
                        lvl = HTFLevel.from_dict(l_data)
                        self.levels[lvl.level_id] = lvl
                    for g_data in data.get("groups", []):
                        grp = HTFLevelGroup.from_dict(g_data)
                        self.groups[grp.group_id] = grp
                    self.consumed_price_zones = data.get("consumed_price_zones", [])
                    logger.info(
                        f"Loaded HTF Level Lifecycle state: {len(self.levels)} levels, "
                        f"{len(self.groups)} groups, {len(self.consumed_price_zones)} consumed zones."
                    )
                except Exception as e:
                    logger.error(f"Failed to load HTF level lifecycle manager state: {e}")
                    self.levels = {}
                    self.groups = {}
                    self.consumed_price_zones = []
            else:
                self.levels = {}
                self.groups = {}
                self.consumed_price_zones = []

    def _save_atomic(self):
        """Thread-safe atomic persistence to disk."""
        os.makedirs(os.path.dirname(os.path.abspath(self.storage_path)), exist_ok=True)
        dir_name = os.path.dirname(os.path.abspath(self.storage_path))
        temp_fd, temp_path = tempfile.mkstemp(dir=dir_name, suffix=".tmp")
        try:
            payload = {
                "levels": [lvl.to_dict() for lvl in self.levels.values()],
                "groups": [grp.to_dict() for grp in self.groups.values()],
                "consumed_price_zones": self.consumed_price_zones
            }
            with os.fdopen(temp_fd, "w", encoding="utf-8") as f:
                json.dump(payload, f, indent=2)
            os.replace(temp_path, self.storage_path)
        except Exception as e:
            logger.error(f"Failed to atomically persist HTF level lifecycle state: {e}")
            if os.path.exists(temp_path):
                try:
                    os.remove(temp_path)
                except Exception:
                    pass

    @staticmethod
    def format_level_id(symbol: str, timeframe: str, box: Dict) -> str:
        """Constructs a deterministic unique level ID for an HTF box."""
        name = str(box.get("text") or box.get("name") or "Level").replace(" ", "_")
        left = box.get("confirmed_formation_time") or box.get("left") or box.get("created_time") or 0
        top = round(float(max(box.get("top", 0), box.get("bottom", 0))), 2)
        bottom = round(float(min(box.get("top", 0), box.get("bottom", 0))), 2)
        return f"{symbol.upper()}_{timeframe.lower()}_{name}_{left}_{top:.2f}_{bottom:.2f}"

    @staticmethod
    def infer_level_type(box: Dict) -> str:
        """Infers 'demand' or 'supply' from box metadata."""
        if "level_type" in box:
            return str(box["level_type"]).lower()
        if "is_bullish" in box:
            return "demand" if box["is_bullish"] else "supply"
        txt = (box.get("text") or box.get("name") or "").upper()
        if any(w in txt for w in ["DEMAND", "RBS", "DOUBLE BOTTOM", "DB"]):
            return "demand"
        if any(w in txt for w in ["SUPPLY", "SBR", "DOUBLE TOP", "DT"]):
            return "supply"
        return "demand"

    @staticmethod
    def check_overlap(top1: float, bot1: float, top2: float, bot2: float) -> bool:
        """Returns True if two price intervals [bot1, top1] and [bot2, top2] overlap."""
        return max(bot1, bot2) <= min(top1, top2)

    # -------------------------------------------------------------------------
    # Rule Two: Level Registration & Overlap Grouping
    # -------------------------------------------------------------------------
    def register_or_update_box(
        self,
        symbol: str,
        timeframe: str,
        box: Dict
    ) -> HTFLevel:
        """
        Registers an HTF box, detects overlaps with existing levels of the same symbol & type,
        and manages collective grouping and consumed-state inheritance.
        """
        with self._lock:
            level_id = self.format_level_id(symbol, timeframe, box)
            level_type = self.infer_level_type(box)
            top = max(float(box.get("top", 0)), float(box.get("bottom", 0)))
            bottom = min(float(box.get("top", 0)), float(box.get("bottom", 0)))
            created_time = box.get("confirmed_formation_time") or box.get("left") or box.get("created_time") or 0

            is_new = False
            if level_id not in self.levels:
                is_new = True
                level = HTFLevel(
                    level_id=level_id,
                    symbol=symbol,
                    timeframe=timeframe,
                    level_type=level_type,
                    top=top,
                    bottom=bottom,
                    created_time=created_time,
                    raw_box=box
                )
                self.levels[level_id] = level
                logger.info(
                    f"[HTF LEVEL CREATED] Level ID: {level_id} Timeframe: {timeframe.upper()} "
                    f"Type: {level_type.upper()} Zone: {bottom:.2f}–{top:.2f}"
                )
            else:
                level = self.levels[level_id]
                level.raw_box = box

            # Check if this level falls into any historically consumed price zone
            for cz in self.consumed_price_zones:
                if cz["symbol"] == symbol.upper() and cz["level_type"] == level_type:
                    if self.check_overlap(level.top, level.bottom, cz["top"], cz["bottom"]):
                        if not level.consumed:
                            level.consumed = True
                            level.status = LevelStatus.CONSUMED
                            level.trade_id = cz.get("trade_id")
                            logger.info(
                                f"[HTF GROUP CONSUMED STATE INHERITED] Level: {level.level_id} "
                                f"Overlaps consumed zone [{cz['bottom']:.2f}–{cz['top']:.2f}] (Trade {cz.get('trade_id')}). "
                                f"Reason: Existing opportunity already consumed"
                            )

            # Recompute overlap groups for this (symbol, level_type)
            self._recalculate_groups_for_type(symbol, level_type)
            self._save_atomic()
            return self.levels[level_id]

    def _recalculate_groups_for_type(self, symbol: str, level_type: str):
        """
        Groups all levels of (symbol, level_type) via connected components.
        Enforces consumed-state inheritance: if any constituent was consumed or if the
        group overlaps a consumed zone, the entire merged group becomes CONSUMED.
        """
        sym_clean = symbol.upper()
        type_clean = level_type.lower()
        active_candidates = [
            lvl for lvl in self.levels.values()
            if lvl.symbol == sym_clean and lvl.level_type == type_clean
        ]
        if not active_candidates:
            return

        # Build adjacency graph based on price overlap
        adj: Dict[str, Set[str]] = {lvl.level_id: set() for lvl in active_candidates}
        for i in range(len(active_candidates)):
            l1 = active_candidates[i]
            for j in range(i + 1, len(active_candidates)):
                l2 = active_candidates[j]
                if self.check_overlap(l1.top, l1.bottom, l2.top, l2.bottom):
                    adj[l1.level_id].add(l2.level_id)
                    adj[l2.level_id].add(l1.level_id)

        visited: Set[str] = set()
        for lvl in active_candidates:
            lid = lvl.level_id
            if lid in visited:
                continue

            # BFS to find connected component
            component: List[str] = []
            queue = [lid]
            visited.add(lid)
            while queue:
                curr = queue.pop(0)
                component.append(curr)
                for neighbor in adj.get(curr, set()):
                    if neighbor not in visited:
                        visited.add(neighbor)
                        queue.append(neighbor)

            comp_levels = [self.levels[cid] for cid in component]
            grp_top = max(l.top for l in comp_levels)
            grp_bot = min(l.bottom for l in comp_levels)

            # Check if any constituent or prior group ID is consumed
            is_group_consumed = any(l.consumed for l in comp_levels)
            trade_id = next((l.trade_id for l in comp_levels if l.trade_id), None)

            # Check overlap against historical consumed price zones
            if not is_group_consumed:
                for cz in self.consumed_price_zones:
                    if cz["symbol"] == sym_clean and cz["level_type"] == type_clean:
                        if self.check_overlap(grp_top, grp_bot, cz["top"], cz["bottom"]):
                            is_group_consumed = True
                            trade_id = cz.get("trade_id")
                            break

            # Find existing group_id if already assigned to any constituent
            existing_grp_ids = {l.group_id for l in comp_levels if l.group_id}
            if existing_grp_ids:
                group_id = sorted(list(existing_grp_ids))[0]
            else:
                first_lvl = sorted(comp_levels, key=lambda x: x.created_time)[0]
                group_id = f"GRP_{sym_clean}_{type_clean}_{first_lvl.timeframe}_{int(first_lvl.created_time)}_{round(grp_top, 2)}_{round(grp_bot, 2)}"

            group = self.groups.get(group_id)
            if not group:
                group = HTFLevelGroup(
                    group_id=group_id,
                    symbol=sym_clean,
                    level_type=type_clean,
                    constituent_ids=component
                )
                self.groups[group_id] = group
            else:
                group.constituent_ids = set(component)

            group.top = grp_top
            group.bottom = grp_bot

            # Determine collective status
            if is_group_consumed:
                group.consumed = True
                group.status = GroupStatus.CONSUMED
                group.trade_id = trade_id
                # Inherit consumed status to all constituents
                for l in comp_levels:
                    if not l.consumed:
                        l.consumed = True
                        l.status = LevelStatus.CONSUMED
                        l.trade_id = trade_id
                        logger.info(
                            f"[HTF GROUP CONSUMED STATE INHERITED] Group ID: {group_id} "
                            f"New overlapping level: {l.level_id} Reason: Existing opportunity already consumed"
                        )
                    else:
                        l.status = LevelStatus.CONSUMED
            else:
                all_invalidated = all(l.status == LevelStatus.INVALIDATED for l in comp_levels)
                any_invalidated = any(l.status == LevelStatus.INVALIDATED for l in comp_levels)
                if all_invalidated:
                    group.status = GroupStatus.INVALIDATED
                elif any_invalidated:
                    group.status = GroupStatus.PARTIALLY_INVALIDATED
                else:
                    group.status = GroupStatus.ACTIVE

            # Assign group_id to constituents
            for l in comp_levels:
                l.group_id = group_id

            if len(component) > 1:
                constituent_descriptions = ", ".join(f"{l.timeframe.upper()} {l.level_type.capitalize()}" for l in comp_levels)
                logger.info(
                    f"[HTF LEVEL GROUPED] Group ID: {group_id} Constituents: {constituent_descriptions} "
                    f"Status: {group.status.value}"
                )

    # -------------------------------------------------------------------------
    # Rule Three: Two Consecutive HTF Candle Closes Invalidation
    # -------------------------------------------------------------------------
    def process_closed_htf_candle(
        self,
        symbol: str,
        timeframe: str,
        candle: Dict,
        htf_sec: int,
        is_completed: bool = True
    ):
        """
        Evaluates one completed HTF candle against all active levels belonging strictly
        to the timeframe that generated the level.
        Prevents double-counting and enforces consecutive-close reset condition.
        """
        if not is_completed:
            return

        with self._lock:
            sym_clean = symbol.upper()
            tf_clean = timeframe.lower()
            c_time = int(candle.get("time", 0))
            c_close = float(candle.get("close", 0.0))

            relevant_levels = [
                lvl for lvl in self.levels.values()
                if lvl.symbol == sym_clean and lvl.timeframe == tf_clean
            ]

            affected_types = set()
            for lvl in relevant_levels:
                # Do not re-evaluate already invalidated or candle before creation
                if lvl.status == LevelStatus.INVALIDATED:
                    continue
                if c_time <= lvl.last_evaluated_htf_time:
                    # Prevent counting the same completed candle twice
                    continue
                if c_time < lvl.created_time:
                    # Candle is prior to level formation
                    continue

                lvl.last_evaluated_htf_time = c_time

                if lvl.level_type == "demand":
                    is_beyond = c_close < lvl.bottom
                else:
                    is_beyond = c_close > lvl.top

                if is_beyond:
                    lvl.consecutive_beyond_closes += 1
                    logger.info(
                        f"[HTF LEVEL INVALIDATION COUNT] Level ID: {lvl.level_id} "
                        f"Timeframe: {tf_clean.upper()} Consecutive closes beyond zone: {lvl.consecutive_beyond_closes}/2"
                    )
                    if lvl.consecutive_beyond_closes >= 2:
                        lvl.status = LevelStatus.INVALIDATED
                        logger.info(
                            f"[HTF LEVEL INVALIDATED] Level ID: {lvl.level_id} "
                            f"Timeframe: {tf_clean.upper()} Reason: Two consecutive {tf_clean.upper()} closes beyond {lvl.level_type} zone"
                        )
                else:
                    # Reset consecutive-close count if candle closes back inside or on non-beyond side
                    lvl.consecutive_beyond_closes = 0

                affected_types.add(lvl.level_type)

            for l_type in affected_types:
                self._recalculate_groups_for_type(sym_clean, l_type)

            self._save_atomic()

    # -------------------------------------------------------------------------
    # Rule One: Successful Trade Execution Consumption
    # -------------------------------------------------------------------------
    def mark_trade_executed(
        self,
        symbol: str,
        timeframe: str,
        box: Dict,
        trade_id: str
    ):
        """
        Permanently marks an HTF level and its collective group as CONSUMED
        immediately upon confirmed order execution.
        """
        with self._lock:
            level_id = self.format_level_id(symbol, timeframe, box)
            level = self.levels.get(level_id)
            if not level:
                # Register first if missing
                level = self.register_or_update_box(symbol, timeframe, box)

            level.consumed = True
            level.status = LevelStatus.CONSUMED
            level.trade_id = trade_id

            grp_id = level.group_id
            group = self.groups.get(grp_id) if grp_id else None

            if group:
                group.consumed = True
                group.status = GroupStatus.CONSUMED
                group.trade_id = trade_id
                # Consume all constituent levels in this collective group
                for cid in group.constituent_ids:
                    c_lvl = self.levels.get(cid)
                    if c_lvl:
                        c_lvl.consumed = True
                        c_lvl.status = LevelStatus.CONSUMED
                        c_lvl.trade_id = trade_id

                # Record persistent consumed zone for inheritance
                cz_entry = {
                    "symbol": level.symbol,
                    "level_type": level.level_type,
                    "top": group.top,
                    "bottom": group.bottom,
                    "trade_id": trade_id,
                    "group_id": group.group_id
                }
                self.consumed_price_zones.append(cz_entry)

                logger.info(
                    f"[HTF LEVEL CONSUMED] Group ID: {group.group_id} Trade ID: {trade_id} "
                    f"Reason: Trade successfully executed"
                )
            else:
                cz_entry = {
                    "symbol": level.symbol,
                    "level_type": level.level_type,
                    "top": level.top,
                    "bottom": level.bottom,
                    "trade_id": trade_id,
                    "group_id": None
                }
                self.consumed_price_zones.append(cz_entry)
                logger.info(
                    f"[HTF LEVEL CONSUMED] Level ID: {level.level_id} Trade ID: {trade_id} "
                    f"Reason: Trade successfully executed"
                )

            self._save_atomic()

    # -------------------------------------------------------------------------
    # Tradability Query
    # -------------------------------------------------------------------------
    def is_box_tradable(self, symbol: str, timeframe: str, box: Dict) -> Tuple[bool, str]:
        """
        Determines if an HTF box is tradable under Rules 1, 2, and 3:
        Returns (is_tradable, reason).
        """
        with self._lock:
            level_id = self.format_level_id(symbol, timeframe, box)
            level = self.levels.get(level_id)
            if not level:
                # If level is not yet registered, register it on the fly
                level = self.register_or_update_box(symbol, timeframe, box)

            if level.consumed:
                return False, f"Level {level_id} is CONSUMED (Trade: {level.trade_id})"

            if level.status == LevelStatus.INVALIDATED:
                return False, f"Level {level_id} is INVALIDATED (Two consecutive closes beyond)"

            grp_id = level.group_id
            if grp_id:
                group = self.groups.get(grp_id)
                if group:
                    if group.consumed:
                        return False, f"Collective Group {grp_id} is CONSUMED (Trade: {group.trade_id})"
                    if group.status == GroupStatus.INVALIDATED:
                        return False, f"Collective Group {grp_id} is INVALIDATED"

            return True, "ACTIVE"

    def clear_for_test(self):
        """Clears in-memory data for deterministic testing."""
        with self._lock:
            self.levels.clear()
            self.groups.clear()
            self.consumed_price_zones.clear()


# Global singleton instance
htf_level_lifecycle_manager = HTFLevelLifecycleManager()
